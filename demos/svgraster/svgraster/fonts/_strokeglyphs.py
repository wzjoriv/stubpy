def _parse(spec: str) -> list[np.ndarray]:
    strokes = []
    for part in spec.split("|"):
        pts = [tuple(float(v) for v in p.split(",")) for p in part.split()]
        if pts:
            strokes.append(np.array(pts, dtype=np.float64))
    return strokes


_CACHE = {ch: _parse(spec) for ch, spec in GLYPHS.items()}
_UNKNOWN = _parse(UNKNOWN)


def glyph(ch: str) -> tuple[list[np.ndarray], float]:
    """Strokes (relative to the baseline origin, grid units) and advance for ``ch``."""
    scale = 1.0
    key = ch
    if ch not in _CACHE and ch.upper() in _CACHE:
        key, scale = ch.upper(), LOWERCASE_SCALE
    strokes = _CACHE.get(key, _UNKNOWN)
    out = []
    for s in strokes:
        pts = s.copy()
        pts[:, 1] -= GRID_HEIGHT
        out.append(pts * scale)
    return out, ADVANCE * scale
