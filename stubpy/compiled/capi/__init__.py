_GENERATED = ("Generated by Cython", "/* Generated by", "// Generated by")


def _folders(module_file: Path) -> list[Path]:
    here = module_file.parent
    return [here, here / "src", here.parent / "src"]


def _readable(path: Path) -> str | None:
    """The text of *path*, or ``None`` for an unreadable or generated (Cython) file."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    return None if any(marker in text[:2048] for marker in _GENERATED) else text


def c_sources(module_file: str | Path) -> list[Path]:
    """Find the C sources an extension module was built from.

    A same-stem source (``_x.c`` for ``_x.cp312-win_amd64.pyd``) next to the module, in a
    ``src/`` folder beside it, or in a ``src/`` folder beside its package is used alone.
    Otherwise the file defining ``PyInit_<stem>`` in one of those folders is used with the
    other C files there that define no other module.

    Parameters
    ----------
    module_file : str or pathlib.Path
        The built extension (or any file named after the module).

    Returns
    -------
    list of pathlib.Path
        The sources, the module's own file first; empty when none is found. Cython output
        is never returned.

    See Also
    --------
    read_c_files : Read the sources found.
    """
    path = Path(module_file)
    stem = module_stem(path)
    folders = [f for f in _folders(path) if f.is_dir()]
    for folder in folders:
        same = [folder / (stem + s) for s in CAPI_SOURCE_SUFFIXES if (folder / (stem + s)).is_file()]
        same = [p for p in same if _readable(p) is not None]
        if same:
            return same[:1]
    for folder in folders:
        candidates = sorted(p for s in CAPI_SOURCE_SUFFIXES for p in folder.glob("*" + s))[:CAPI_MAX_SOURCES]
        texts = {p: _readable(p) for p in candidates}
        texts = {p: t for p, t in texts.items() if t is not None}
        owner = next((p for p, t in texts.items() if f"PyInit_{stem}(" in t or f"PyInit_{stem} (" in t), None)
        if owner is not None:
            return [owner, *(p for p, t in texts.items() if p != owner and "PyInit_" not in t)]
    return []


def read_c_files(paths: list[Path]) -> CModule:
    """Read several C sources of one extension as a single text.

    Parameters
    ----------
    paths : list of pathlib.Path
        The sources, as :func:`c_sources` returns them.

    Returns
    -------
    CModule
        What :func:`read_c_source` finds in the joined text.

    See Also
    --------
    read_c_source : The same for one source text.
    """
    texts = [_readable(p) for p in paths]
    return read_c_source("\n".join(t for t in texts if t))


@functools.lru_cache(maxsize=32)
def _cached(key: tuple[tuple[str, float], ...]) -> CModule:
    return read_c_files([Path(p) for p, _ in key])


def _for(module: types.ModuleType) -> CModule | None:
    """The C sources' view of *module*, or ``None`` when it has no C sources."""
    origin = getattr(module, "__file__", None)
    if not origin or Path(origin).suffix in (".py", ".pyx"):
        return None
    try:
        sources = c_sources(origin)
        key = tuple((str(p), p.stat().st_mtime) for p in sources)
    except (OSError, ValueError):
        return None
    if not key:
        return None
    try:
        return _cached(key)
    except (RecursionError, ValueError):
        return None


def capi_signatures(module: types.ModuleType) -> dict[str, tuple[Signature, str | None]]:
    """``{qualified name: (signature, None)}`` from the C sources beside *module*'s file; empty without any."""
    found = _for(module)
    return {name: (sig, None) for name, sig in found.signatures.items()} if found is not None else {}


def capi_attribute_types(module: types.ModuleType) -> dict[str, str]:
    """``{Class.attribute: type}`` for the getsets and members in the C sources beside *module*'s file."""
    found = _for(module)
    return dict(found.attributes) if found is not None else {}
