"""
Stub-only distributions (PEP 561): ``<pkg>-stubs`` folders with a ``pyproject.toml`` and a partial ``py.typed``.
"""
from __future__ import annotations

import importlib.metadata
from pathlib import Path, PurePath

from stubpy.config.options import Config

from .results import Report

STUBS_SUFFIX = "-stubs"
PY_TYPED = "partial\n"


def distribution_path(relative: PurePath) -> PurePath:
    """Move a stub path relative to the output root into its stub-only distribution.

    Examples
    --------
    >>> from pathlib import PurePosixPath
    >>> distribution_path(PurePosixPath("pkg/sub/mod.pyi")).as_posix()
    'pkg-stubs/pkg-stubs/sub/mod.pyi'
    >>> distribution_path(PurePosixPath("mod.pyi")).as_posix()
    'mod-stubs/mod-stubs/__init__.pyi'
    """
    top, *rest = relative.parts
    if not rest:
        name = top.removesuffix(".pyi")
        return type(relative)(name + STUBS_SUFFIX, name + STUBS_SUFFIX, "__init__.pyi")
    name = top + STUBS_SUFFIX
    return type(relative)(name, name, *rest)


def finish_distributions(report: Report, out: Path, config: Config) -> None:
    """Write (``generate``) or compare (``check``) the ``py.typed`` and ``pyproject.toml`` of each distribution in *report*.

    They are not counted as stubs; a missing or different one is stale under ``check``.
    """
    from ._output import write_atomic

    packages: dict[Path, set[str]] = {}
    for result in report.results:
        if result.output is None or not result.ok:
            continue
        try:
            parts = result.output.relative_to(out).parts
        except ValueError:
            continue
        if len(parts) < 3 or not parts[0].endswith(STUBS_SUFFIX):
            continue
        folders = packages.setdefault(out / parts[0], set())
        for depth in range(2, len(parts)):
            folders.add(".".join(parts[1:depth]))
    for dist, folders in sorted(packages.items()):
        name = dist.name
        for path, text in ((dist / name / "py.typed", PY_TYPED),
                           (dist / "pyproject.toml", _pyproject(name, sorted(folders), config))):
            if report.action == "check":
                if not path.is_file() or path.read_text(encoding="utf-8") != text:
                    report.stale.append(path)
            else:
                write_atomic(path, text)


def _pyproject(name: str, packages: list[str], config: Config) -> str:
    """The ``pyproject.toml`` of the stub-only distribution *name*, built with setuptools."""
    listed = ", ".join(f'"{p}"' for p in packages)
    return (
        '[build-system]\nrequires = ["setuptools>=61"]\nbuild-backend = "setuptools.build_meta"\n\n'
        f'[project]\nname = "{name}"\nversion = "{_version(name.removesuffix(STUBS_SUFFIX))}"\n'
        f'description = "Type stubs for {name.removesuffix(STUBS_SUFFIX)}, generated by stubpy"\n'
        f'requires-python = ">={config.target_python}"\n\n'
        f'[tool.setuptools]\npackages = [{listed}]\n\n'
        '[tool.setuptools.package-data]\n"*" = ["*.pyi", "py.typed"]\n'
    )


def _version(package: str) -> str:
    """The installed version of the distribution that provides *package*; ``"0"`` when none does."""
    for dist in importlib.metadata.packages_distributions().get(package, ()):
        try:
            return importlib.metadata.version(dist)
        except importlib.metadata.PackageNotFoundError:
            continue
    return "0"
