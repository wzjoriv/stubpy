"""Incremental merge: marked regions are refreshed, everything else is kept byte for byte, nothing unsafe is written."""
from __future__ import annotations

import ast
import random

import pytest

import stubpy
from stubpy.config import Config
from stubpy.merge import BEGIN_MARKER, END_MARKER, MergeError, merge_stubs, read_and_merge, wrap_generated

B, E = BEGIN_MARKER, END_MARKER


def _region(body: str, indent: str = "") -> str:
    return f"{indent}{B}\n{body}{indent}{E}\n"


class TestMarkers:
    @pytest.mark.parametrize("begin, end", [
        (B, E),
        ("#  STUBPY: AUTO-GENERATED BEGIN", "# stubpy auto generated end"),
        (B + "   ", E + "\t"),
        ("# stubpy:autogenerated begin", "# stubpy:autogenerated end"),
    ])
    def test_spellings(self, begin, end):
        existing = f"x: int\n{begin}\nold: int\n{end}\n"
        assert merge_stubs(existing, "new: str\n").text == f"x: int\n{begin}\nnew: str\n{end}\n"

    def test_crlf_is_kept(self):
        existing = f"# hand\r\n{B}\r\nold: int\r\n{E}\r\ny: int\r\n"
        text = merge_stubs(existing, "a: int\n\ndef f() -> None: ...\n").text
        assert text == f"# hand\r\n{B}\r\na: int\r\n\r\ndef f() -> None: ...\r\n{E}\r\ny: int\r\n"

    def test_bom_is_kept(self):
        existing = f"\ufeff{B}\nold: int\n{E}\n"
        assert merge_stubs(existing, "new: int\n").text == f"\ufeff{B}\nnew: int\n{E}\n"

    def test_non_markers_are_ignored(self):
        assert merge_stubs("# stubpy: something else\nx: int\n", "y: int\n").text is None


class TestUnsafeInput:
    @pytest.mark.parametrize("existing, message", [
        (f"{B}\n{B}\nx: int\n{E}\n{E}\n", "nested begin marker on line 2"),
        (f"x: int\n{E}\n", "end marker on line 2 has no begin"),
        (f"{B}\nx: int\n", "begin marker on line 1 has no end"),
        (f"class C:\n    {B}\n    x: int\n{E}\n", "not indented like its begin"),
        (f"def broken(:\n{B}\n{E}\n", "does not parse outside"),
    ])
    def test_raises_a_clear_error(self, existing, message):
        with pytest.raises(MergeError, match=message):
            merge_stubs(existing, "y: int\n")

    def test_file_is_left_alone_with_an_error(self, tmp_path):
        path = tmp_path / "m.pyi"
        raw = f"{B}\nx: int\n".encode()
        path.write_bytes(raw)
        result = read_and_merge(path, "y: int\n")
        assert result.text is None and not result.ok
        assert "no end" in result.notes[0].message
        assert path.read_bytes() == raw

    def test_unmarked_file_is_hand_written(self, tmp_path):
        path = tmp_path / "m.pyi"
        path.write_text("def f() -> int: ...\n")
        result = read_and_merge(path, "def g() -> int: ...\n")
        assert result.text is None and result.ok
        assert result.notes[0].level == "warning" and "hand-written" in result.notes[0].message


class TestRegions:
    def test_outside_is_kept_byte_for_byte(self):
        before, between, after = "# top\nimport os  # keep\n\n", "\n\n# middle   \nX = 1\n", "\n# tail"
        existing = before + _region("a: int\n") + between + _region("b: int\n") + after
        text = merge_stubs(existing, "a: str\nb: str\n").text
        assert text == before + _region("a: str\n") + between + _region("b: str\n") + after

    def test_definitions_stay_in_their_region_and_new_ones_follow_their_predecessor(self):
        existing = _region("def a() -> None: ...\n") + "\nX = 1\n\n" + _region("def b() -> None: ...\n")
        generated = "def a() -> int: ...\n\ndef b() -> int: ...\n\ndef c() -> int: ...\n"
        text = merge_stubs(existing, generated).text
        first, second = text.split("X = 1")
        assert "def a() -> int" in first and "def b" not in first
        assert "def b() -> int: ...\n\ndef c() -> int: ..." in second

    def test_imports_go_to_the_first_region(self):
        existing = _region("") + "\n" + _region("def f() -> None: ...\n")
        text = merge_stubs(existing, "from os import PathLike\n\ndef f(p: PathLike) -> None: ...\n").text
        assert text.index("from os import PathLike") < text.index("\n\n")

    def test_renamed_and_removed_symbols(self):
        existing = _region("def old() -> None: ...\n\nclass Gone: ...\n")
        text = merge_stubs(existing, "def new() -> None: ...\n").text
        assert "def new" in text and "old" not in text and "Gone" not in text

    def test_hand_written_definition_wins(self):
        existing = "def f(x: int) -> int: ...  # by hand\n\n" + _region("def f() -> None: ...\n")
        result = merge_stubs(existing, "def f() -> None: ...\n\ndef g() -> None: ...\n")
        assert result.text.count("def f") == 1 and "# by hand" in result.text and "def g" in result.text
        assert [n.level for n in result.notes] == ["info"] and "f is written by hand" in result.notes[0].message

    def test_class_body_region(self):
        existing = (
            "class Widget:\n"
            "    def manual(self) -> str: ...\n"
            f"    {B}\n"
            "    def old(self) -> None: ...\n"
            f"    {E}\n"
            "\n"
            "def helper() -> None: ...\n"
        )
        generated = (
            "class Widget:\n    def manual(self) -> int: ...\n    def size(self) -> int: ...\n"
            "    @property\n    def name(self) -> str: ...\n\ndef helper() -> int: ...\n"
        )
        result = merge_stubs(existing, generated)
        assert result.text == (
            "class Widget:\n"
            "    def manual(self) -> str: ...\n"
            f"    {B}\n"
            "    def size(self) -> int: ...\n"
            "    @property\n"
            "    def name(self) -> str: ...\n"
            f"    {E}\n"
            "\n"
            "def helper() -> None: ...\n"
        )
        assert "Widget.manual is written by hand" in result.notes[0].message

    def test_emptied_class_region_stays_valid(self):
        existing = f"class C:\n    {B}\n    def m(self) -> None: ...\n    {E}\n"
        text = merge_stubs(existing, "x: int\n").text
        ast.parse(text)
        assert f"    {B}\n    ...\n    {E}\n" in text

    def test_module_and_class_regions_together(self):
        existing = _region("") + f"\nclass C:\n    {B}\n    {E}\n"
        text = merge_stubs(existing, "import os\n\nclass C:\n    x: int\n\ndef f() -> None: ...\n").text
        assert text.startswith(f"{B}\nimport os\n\ndef f() -> None: ...\n{E}\n")
        assert f"class C:\n    {B}\n    x: int\n    {E}\n" in text
        ast.parse(text)

    def test_wrap_generated(self):
        assert wrap_generated("x: int") == f"{B}\nx: int\n{E}\n"
        assert wrap_generated(f"{B}\nx\n{E}\n") == f"{B}\nx\n{E}\n"


class TestIncrementalRuns:
    def _gen(self, src, *args, **cfg):
        return stubpy.generate(str(src), *args, config=Config(incremental=True, **cfg))

    def test_first_run_creates_a_marked_stub_and_reruns_are_stable(self, tmp_path):
        src = tmp_path / "m.py"
        src.write_text("def f(x: int) -> int: ...\n")
        assert self._gen(src).ok
        text = (tmp_path / "m.pyi").read_text()
        assert text == f"{B}\ndef f(x: int) -> int: ...\n{E}\n"
        assert self._gen(src).ok and (tmp_path / "m.pyi").read_text() == text
        assert stubpy.check(str(src), config=Config(incremental=True)).ok

    def test_check_compares_only_the_regions(self, tmp_path):
        src = tmp_path / "m.py"
        src.write_text("def f(x: int) -> int: ...\n")
        self._gen(src)
        stub = tmp_path / "m.pyi"
        stub.write_bytes(b"# my notes\r\n" + stub.read_bytes() + b"\r\nEXTRA: int\r\n")
        assert stubpy.check(str(src), config=Config(incremental=True)).ok
        src.write_text("def f(x: str) -> int: ...\n")
        assert stubpy.check(str(src), config=Config(incremental=True)).stale == [stub]

    def test_unsafe_stub_is_an_error_and_untouched(self, tmp_path):
        src = tmp_path / "m.py"
        src.write_text("x: int = 1\n")
        stub = tmp_path / "m.pyi"
        stub.write_bytes(f"{B}\n{B}\n".encode())
        report = self._gen(src)
        assert not report.ok and report.written == []
        assert "nested begin" in report.failed[0].errors[0].message
        assert stub.read_bytes() == f"{B}\n{B}\n".encode()

    def test_no_temporary_files_are_left(self, tmp_path):
        src = tmp_path / "m.py"
        src.write_text("x: int = 1\n")
        self._gen(src)
        stubpy.generate(str(src))
        assert sorted(p.name for p in tmp_path.iterdir()) == ["m.py", "m.pyi"]


_HAND = ["# note {n}\n", "LIMIT_{n}: int\n", "\n", "def by_hand_{n}() -> None: ...\n", "   # spaced {n}   \n",
         "class Manual{n}:\n    x: int\n"]


@pytest.mark.parametrize("seed", range(12))
def test_hand_edits_outside_markers_survive_any_number_of_regenerations(tmp_path, seed):
    rng = random.Random(seed)
    src = tmp_path / "m.py"
    stub = tmp_path / "m.pyi"
    newline = rng.choice(["\n", "\r\n"])
    for run in range(6):
        names = rng.sample(["alpha", "beta", "gamma", "delta"], rng.randint(1, 4))
        src.write_text("".join(f"def {n}(x: int = {run}) -> int: ...\n" for n in names))
        report = stubpy.generate(str(src), config=Config(incremental=True))
        assert report.ok, report.summary()
        raw = stub.read_bytes().decode()
        begin, end = raw.index(B), raw.index(E) + len(E)
        head, region, tail = raw[:begin], raw[begin:end], raw[end:]
        assert all(f"def {n}(x: int = {run})" in region for n in names)
        head += "".join(rng.choice(_HAND).format(n=f"{run}h").replace("\n", newline) for _ in range(rng.randint(0, 3)))
        tail += "".join(rng.choice(_HAND).format(n=f"{run}t").replace("\n", newline) for _ in range(rng.randint(0, 3)))
        stub.write_bytes((head + region + tail).encode())
        expected_head, expected_tail = head, tail
        assert stubpy.generate(str(src), config=Config(incremental=True)).ok
        again = stub.read_bytes().decode()
        assert again.startswith(expected_head) and again.endswith(expected_tail)
